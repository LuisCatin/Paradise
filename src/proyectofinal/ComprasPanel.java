    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int[] list = jTable1.getSelectedRows();
        for (int i = 0; i < list.length; i++) {
            Compra.INSTANCE.delete(e.getCompras().get(list[i]));
        }
        e.updateCompras();
        update();
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        Frame parentFrame = (Frame) SwingUtilities.getWindowAncestor(this);
        int pos = jTable1.getSelectedRow();
        Compra p = new Compra(e.getCompras().get(pos).getIdCompra(), e.getCompras().get(pos).getFecha(), e.getCompras().get(pos).getProveedor(), e.getCompras().get(pos).getBodega());
        ComprasDialog bd = new ComprasDialog(parentFrame, true, p);
        bd.setLocationRelativeTo(parentFrame);
        bd.setVisible(true);
        e.updateCompras();
        update();
    }//GEN-LAST:event_jButton4ActionPerformed


