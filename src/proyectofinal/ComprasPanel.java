    public void update() {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for (int i = 0; i < e.getCompras().size(); i++) {
            Object[] rowData = {
                e.getCompras().get(i).getIdCompra(),
                e.getCompras().get(i).getFecha(),
                e.getCompras().get(i).getProveedor().getNombreEmpresa(),
                e.getCompras().get(i).getProveedor().getEmail(),
                e.getCompras().get(i).getBodega().getNombreBodega()
            };
            modelo.addRow(rowData);
        }
    }

